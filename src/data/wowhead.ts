export function iconUrl(name: string, size: 'small' | 'medium' | 'large' = 'medium') {
  const entry = WOWHEAD[name]
  return entry ? `https://wow.zamimg.com/images/wow/icons/${size}/${entry[1]}.jpg` : null
}

export function wowheadUrl(name: string) {
  const entry = WOWHEAD[name]
  return entry ? `https://www.wowhead.com/forever/item=${entry[0]}` : null
}
